"""Reproducible 2025-26 betting-rule comparison using genuine pre-tipoff inputs.

CSV input columns:
game_id,tipoff_utc,predicted_at_utc,home_win_probability,away_win_probability,
home_decimal,away_decimal,odds_captured_at_utc,actual_winner_side

Rows must contain predictions generated by a historical walk-forward model,
not retrospectively fitted probabilities. Odds must be captured before tipoff.
"""
import argparse
import csv
import datetime as dt
import json
from pathlib import Path

START=dt.datetime(2025,10,1,tzinfo=dt.timezone.utc)
END=dt.datetime(2026,7,1,tzinfo=dt.timezone.utc)

def stamp(s):
    t=dt.datetime.fromisoformat(s.replace("Z","+00:00"))
    if t.tzinfo is None:
        raise ValueError("timestamps must include UTC offset")
    return t.astimezone(dt.timezone.utc)

def run(path):
    with Path(path).open(newline="",encoding="utf-8") as f:
        rows=list(csv.DictReader(f))
    if not rows:
        raise ValueError("Historical pre-tipoff dataset empty; cannot claim backtest")
    results={"old_rules":{"bankroll_aud":100.0,"bets":0,"wins":0,"losses":0,"max_drawdown_pct":0.0},
             "new_rules":{"bankroll_aud":100.0,"bets":0,"wins":0,"losses":0,"max_drawdown_pct":0.0}}
    seen=set()
    rows.sort(key=lambda r:(r["tipoff_utc"],r["game_id"]))
    for r in rows:
        tip=stamp(r["tipoff_utc"])
        pred=stamp(r["predicted_at_utc"])
        odds=stamp(r["odds_captured_at_utc"])
        if not START<=tip<END or not pred<tip or not odds<tip:
            raise ValueError("Out-of-season or post-tipoff data: "+r["game_id"])
        if r["game_id"] in seen:
            raise ValueError("Duplicate game "+r["game_id"])
        seen.add(r["game_id"])
        hp=float(r["home_win_probability"])
        ap=float(r["away_win_probability"])
        h=float(r["home_decimal"])
        a=float(r["away_decimal"])
        if not (0<hp<1 and 0<ap<1 and abs(hp+ap-1)<.001 and 1<h<1000 and 1<a<1000):
            raise ValueError("Invalid probability or odds for "+r["game_id"])
        actual=r["actual_winner_side"]
        if actual not in ("home","away"):
            raise ValueError("Unknown actual winner "+r["game_id"])
        options=[("home",hp,h,hp*h-1),("away",ap,a,ap*a-1)]
        winner="home" if hp>=ap else "away"
        old=max(options,key=lambda q:q[3])
        new=next(q for q in options if q[0]==winner)
        for name,q,eligible in (
            ("old_rules",old,old[3]>=.05),
            ("new_rules",new,new[1]>=.60 and new[2]<=2.0 and new[3]>=.08)):
            if not eligible:
                continue
            s=results[name]
            stake=round(s["bankroll_aud"]*.01,2)
            if stake<=0: continue
            won=q[0]==actual
            profit=round(stake*(q[2]-1),2) if won else -stake
            s["bankroll_aud"]=round(s["bankroll_aud"]+profit,2)
            s["bets"]+=1
            s["wins" if won else "losses"]+=1
            peak=s.setdefault("_peak",100.0)
            peak=max(peak,s["bankroll_aud"])
            s["_peak"]=peak
            s["max_drawdown_pct"]=round(max(s["max_drawdown_pct"],100*(peak-s["bankroll_aud"])/peak),2)
    for v in results.values():
        v.pop("_peak",None)
        v["profit_aud"]=round(v["bankroll_aud"]-100,2)
        v["roi_pct"]=v["profit_aud"]
    output={"season":"2025-26","games":len(rows),"comparison":results,
        "limitations":"Requires genuine walk-forward historical probabilities and time-stamped pre-tipoff odds. "
        "Single-bet sequential simulation; does not reproduce concurrent exposure caps. "
        "Input authenticity must be independently verified."}
    print(json.dumps(output,indent=2))
    return output

if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--input",required=True,help="Verified historical predictions and odds CSV")
    args=parser.parse_args()
    run(args.input)
